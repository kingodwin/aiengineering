student_score = 100

if student_score < 0 or student_score > 100:
    print("Invalid score")

elif student_score >= 70:
    print("Grade A")

elif student_score >= 60:
    print("Grade B")

elif student_score >= 50:
    print("Grade C")

elif student_score >= 45:
    print("Grade D")

else:
    print("Grade F")


    
